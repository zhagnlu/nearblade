import { readFileSync, writeFileSync } from 'node:fs';
import { languageCodes } from './extract-locales.mjs';

// Included in the Nginx http context, before the site's server block.
export function renderLocaleNginx() {
  const pages = Object.keys(JSON.parse(readFileSync(new URL('../content/seo/pages.json', import.meta.url), 'utf8')));
  const retired = { '/products/sb-002': '/products/sb-001', '/products/tb-001': '/products/cp-001' };
  const localize = (path, prefix) => `/${prefix}${path === '/' ? '/' : path}`;
  const variants = path => path === '/' ? ['/', '/index.html'] : path.endsWith('/') ? [path.slice(0, -1), path, `${path}index.html`] : [path, `${path}/`, `${path}/index.html`];
  const targets = new Map();
  for (const page of [...pages, ...Object.keys(retired)]) {
    const target = retired[page] || page;
    for (const alias of variants(page)) targets.set(alias, localize(target, '$nearblade_legacy_locale'));
    for (const code of languageCodes) {
      const prefix = code.toLowerCase();
      for (const alias of variants(localize(page, prefix))) targets.set(alias, localize(target, prefix));
    }
  }
  const lines = [
    '# GENERATED by scripts/render-locale-nginx.mjs; include in the http context.',
    '# Do not publish as website content. See docs/i18n/language-pages.md.',
    'map_hash_bucket_size 128;', 'map_hash_max_size 8192;', 'map $arg_lang $nearblade_legacy_locale {', '    default en;',
    ...languageCodes.map(code => `    ~*^${code}$ ${code.toLowerCase()};`), '}',
    'map $args $nearblade_clean_args {', '    default $args;',
    '    ~^lang=[^&]*$ "";',
    '    ~^lang=[^&]*&(?<nearblade_after>.*)$ $nearblade_after;',
    '    ~^(?<nearblade_before>.+)&lang=[^&]*$ $nearblade_before;',
    '    ~^(?<nearblade_left>.+)&lang=[^&]*&(?<nearblade_right>.+)$ "$nearblade_left&$nearblade_right";', '}',
    'map $nearblade_clean_args $nearblade_query_suffix {', '    "" "";', '    default "?$nearblade_clean_args";', '}',
    'map $args $nearblade_has_lang {', '    default 0;', '    ~(^|&)lang= 1;', '}',
    'map $uri $nearblade_page_target {', '    default "";',
    ...[...targets].map(([from, to]) => `    ${from} ${to};`), '}',
    // Regex entries make canonical matching case-sensitive; literal map keys are not.
    'map $uri $nearblade_is_canonical {', '    default 0;',
    ...languageCodes.flatMap(code => pages.map(page => `    ~^${localize(page, code.toLowerCase()).replaceAll('.', '\\.').replaceAll('/', '\\/')}$ 1;`)), '}',
    'map "$nearblade_is_canonical|$nearblade_has_lang|$nearblade_page_target" $nearblade_redirect {',
    '    default 1;', '    ~\\|$ 0;', '    ~^1\\|0\\| 0;', '}',
    'map $uri $nearblade_error_page {', '    default /en/404.html;',
    ...languageCodes.map(code => `    ~*^/${code.toLowerCase()}(?:/|$) /${code.toLowerCase()}/404.html;`), '}', '',
  ];
  writeFileSync(new URL('../deploy/multilingual-maps.conf', import.meta.url), lines.join('\n'));
}
if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) renderLocaleNginx();
